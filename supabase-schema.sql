create extension if not exists pgcrypto;

create table if not exists members (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  father_name text,
  mobile text,
  join_date date,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now()
);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  member_id uuid not null references members(id) on delete cascade,
  year integer not null,
  month integer not null check(month between 1 and 12),
  required_amount numeric(12,2) not null default 500,
  paid_amount numeric(12,2) not null default 0,
  payment_date date,
  created_at timestamptz not null default now(),
  unique(member_id, year, month)
);

create table if not exists profits (
  id bigint generated by default as identity primary key,
  year integer not null unique,
  total_profit numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists expenses (
  id bigint generated by default as identity primary key,
  year integer not null,
  date date not null,
  description text not null,
  amount numeric(14,2) not null,
  created_at timestamptz not null default now()
);

create table if not exists investments (
  id bigint generated by default as identity primary key,
  year integer not null,
  date date not null,
  description text not null,
  amount numeric(14,2) not null,
  created_at timestamptz not null default now()
);

create table if not exists member_settlements (
  id bigint generated by default as identity primary key,
  member_id uuid not null references members(id),
  settlement_date date not null default current_date,
  amount_paid numeric(14,2) not null,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists assets (
  id bigint generated by default as identity primary key,
  year integer not null,
  date date not null default current_date,
  category text not null,
  description text not null,
  amount numeric(14,2) not null,
  status text not null default 'active' check(status in ('active','sold','returned')),
  created_at timestamptz not null default now()
);

create table if not exists notices (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  publish_date date not null default current_date,
  status text not null default 'published' check(status in ('published','draft')),
  created_at timestamptz not null default now()
);

create table if not exists settings (
  id boolean primary key default true,
  organization_name text not null default 'আল ইখওয়ান ইসলামী সংস্থা বাংলাদেশ',
  monthly_contribution numeric(10,2) not null default 500,
  start_year integer not null default 2021
);

create table if not exists admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check(role='admin'),
  created_at timestamptz not null default now()
);

